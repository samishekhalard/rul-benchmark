"""
Aggregate per-run JSON files into a ranked Markdown results table.

Usage:
    python src/report.py --results-dir results/raw --output results/RESULTS.md
"""

from __future__ import annotations

import argparse
import json
from collections import defaultdict
from pathlib import Path

import numpy as np


def load_results(results_dir: Path) -> list[dict]:
    records = []
    for f in sorted(results_dir.glob("*.json")):
        with open(f) as fh:
            records.append(json.load(fh))
    return records


def aggregate(records: list[dict]) -> list[dict]:
    """Group by (subset, model), aggregate metrics across seeds."""
    groups: dict[tuple, list[dict]] = defaultdict(list)
    for r in records:
        groups[(r["subset"], r["model"])].append(r)

    def _agg(runs: list[dict], key: str) -> tuple[float, float]:
        vals = [r[key] for r in runs if key in r]
        return float(np.mean(vals)), float(np.std(vals))

    rows = []
    for (subset, model), runs in groups.items():
        rmse_m, rmse_s = _agg(runs, "rmse")
        mae_m, mae_s = _agg(runs, "mae")
        r2_m, r2_s = _agg(runs, "r2")
        phm_m, phm_s = _agg(runs, "phm_score")

        n_params = runs[0].get("n_params", 0)
        times = [r["train_time_s"] for r in runs]
        time_str = f"{np.mean(times):.1f}s"

        rows.append({
            "subset": subset,
            "model": model,
            "rmse": rmse_m,
            "rmse_s": rmse_s,
            "mae": mae_m,
            "mae_s": mae_s,
            "r2": r2_m,
            "r2_s": r2_s,
            "phm": phm_m,
            "phm_s": phm_s,
            "n_params": n_params,
            "time": time_str,
            "n_seeds": len(runs),
        })

    rows.sort(key=lambda r: (r["subset"], r["rmse"]))
    return rows


def render_table(rows: list[dict]) -> str:
    header = (
        "| Subset | Model | RMSE | MAE | R² | PHM Score | Params | Train Time | Seeds |\n"
        "|--------|-------|------|-----|----|-----------|--------|------------|-------|\n"
    )
    lines = [header]
    for r in rows:
        def fmt(m, s):
            return f"{m:.2f} ± {s:.2f}"
        line = (
            f"| {r['subset']} | {r['model']} "
            f"| {fmt(r['rmse'], r['rmse_s'])} "
            f"| {fmt(r['mae'], r['mae_s'])} "
            f"| {fmt(r['r2'], r['r2_s'])} "
            f"| {fmt(r['phm'], r['phm_s'])} "
            f"| {r['n_params']:,} "
            f"| {r['time']} "
            f"| {r['n_seeds']} |\n"
        )
        lines.append(line)
    return "".join(lines)


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--results-dir", default="results/raw")
    p.add_argument("--output", default="results/RESULTS.md")
    args = p.parse_args()

    results_dir = Path(args.results_dir)
    records = load_results(results_dir)
    if not records:
        print(f"No JSON files found in {results_dir}. Run training first.")
        return

    rows = aggregate(records)
    table = render_table(rows)

    output = Path(args.output)
    output.parent.mkdir(parents=True, exist_ok=True)

    content = f"""# Benchmark Results

Generated by `src/report.py` from {len(records)} run(s) in `{results_dir}`.

Metrics are mean ± std across seeds. Sorted by RMSE (ascending) within each subset.

{table}

> PHM Score is the asymmetric PHM 2008 penalty (lower is better).
> Late predictions are penalised more heavily than early ones of the same magnitude.
> See README for the full formula.
"""
    output.write_text(content)
    print(f"Wrote {output} ({len(rows)} rows)")


if __name__ == "__main__":
    main()
